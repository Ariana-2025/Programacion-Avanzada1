    private void btn_ProcesarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_ProcesarActionPerformed
        // TODO add your handling code here:

    try {

        double monto = Double.parseDouble(txt_MontoRetirar.getText());

        if (monto <= 0) {
            JOptionPane.showMessageDialog(this,
                "Ingrese un monto válido");
            return;
        }

        setProcesando(true);

        ProcesoRetiroHilo hilo = new ProcesoRetiroHilo(
            cuenta,
            monto,
            new ProcesoRetiroHilo.ProcesoListener() {

                @Override
                public void onInicio() {
                    SwingUtilities.invokeLater(() -> {
                        lbl_Accion.setText("Procesando retiro...");
                    });
                }

                @Override
                public void onExito(double nuevoSaldo) {
                    SwingUtilities.invokeLater(() -> {

                        lbl_Accion.setText("Retiro exitoso");

                        JOptionPane.showMessageDialog(
                            TransaccionForm.this,
                            "Retiro realizado correctamente.\n" +
                            "Nuevo saldo: $" + nuevoSaldo
                        );

                        setProcesando(false);
                    });
                }

                @Override
                public void onError(String error) {
                    SwingUtilities.invokeLater(() -> {

                        lbl_Accion.setText("Error en el retiro");

                        JOptionPane.showMessageDialog(
                            TransaccionForm.this,
                            error
                        );

                        setProcesando(false);
                    });
                }
            }
        );

        new Thread(hilo).start();

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(this,
            "Ingrese un monto numérico válido");
    }

    }//GEN-LAST:event_btn_ProcesarActionPerformed

